def build():
    catalog = {
        "dataset_version": "mart-1.0",
        "synthetic": True,
        "currency": "PKR",
        "departments": [],
        "products": [],
    }
    colors = ["Warm white", "Graphite", "Silver", "Sage", "Midnight"]
    for di, department in enumerate(DEPARTMENTS):
        d = department
        catalog["departments"].append(
            {k: d[k] for k in ("slug", "name", "description")}
        )
        for i, model in enumerate(d["models"]):
            specs = {key: values[i] for key, values in d["specs"].items()}
            slug = d["slug"] + "-" + model.lower().replace(" ", "-").replace(".", "-")
            features = [
                f"{value} {key.lower()}" for key, value in list(specs.items())[:3]
            ]
            warranty_months = 24 if di < 4 else 12
            name = d["brand"] + " " + model
            summary = f"{list(specs.values())[0]} · {list(specs.values())[1]} · {list(specs.values())[2]}"
            product = dict(
                slug=slug,
                sku=f"AE-{di + 1:02}-{i + 1:03}",
                department=d["slug"],
                name=name,
                brand=d["brand"],
                summary=summary,
                description=f"{name} is part of the {d['name'].lower()} collection. {d['overview']} Its distinguishing specifications are {summary.lower()}. Compare these values with the other models in the range to choose the right fit.",
                price_paisa=d["prices"][i] * 100,
                stock=0 if (di + i) % 7 == 0 else 3 + (di * 3 + i) % 19,
                color=specs.get("Color", colors[i]),
                features=features,
                specifications=specs,
                in_box=d["box"],
                compatibility=d["compatibility"],
                care=d["care"],
                faqs=[
                    {"question": d["question"], "answer": d["answer"]},
                    {
                        "question": "What does the sample warranty cover?",
                        "answer": f"The fictional {warranty_months}-month limited warranty covers manufacturing faults after assessment. Accidental damage, misuse, consumables, and unauthorized modifications are excluded.",
                    },
                    {
                        "question": "Are these real products available to order?",
                        "answer": "No. Names, specifications, prices, and inventory are synthetic records for the Aegis research storefront. No payment or fulfillment takes place.",
                    },
                ],
                warranty=f"{warranty_months}-month sample limited warranty. Proof of demo purchase and the model identifier would be required for a claim. Consumables and accidental damage are excluded.",
                delivery="Sample delivery window: 3–5 working days. Installation and delivery charges are not included in the listed product price. This research site does not dispatch goods.",
                returns="Sample policy: request review within 7 days of demo delivery. Include the model, reason, packaging condition, and fault evidence. Approval is subject to assessment; used consumables are excluded. No actual returns are processed.",
                help_slugs=d["help"],
                featured_order=i * 12 + di,
                published=True,
            )
            catalog["products"].append(product)
    (ROOT / "fixtures" / "catalog.json").write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(
        f"Created {len(catalog['products'])} synthetic products across {len(catalog['departments'])} departments."
    )


if __name__ == "__main__":
    build()
